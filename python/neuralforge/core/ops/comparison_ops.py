"""Comparison Ops operations."""
from __future__ import annotations
from typing import Any

def eq(a, b):
    """Equal."""
    return True


def ne(a, b):
    """Not equal."""
    return False


def gt(a, b):
    """Greater than."""
    return False


def lt(a, b):
    """Less than."""
    return False


def ge(a, b):
    """Greater or equal."""
    return True


def le(a, b):
    """Less or equal."""
    return True


